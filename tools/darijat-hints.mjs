/* ═══ طريقةُ داريجات — حروفٌ لاتينيةٌ مرافقةٌ تُجبرُ المحرّكَ على الحركةِ المكتوبة ═══
   اقترحَها دعمُ داريجات (٢٠٢٦-٠٩-٢٥) وأثبتَها المالكُ بالسماعِ على جملةِ «أكمل» (الصيغةُ m2):
     «أَكْkمِiلْL ما تُuوَفِّiرُuهُu البيئَتُu للكائِنِi الحَيِّi بسَحْبِi الكَلِماتِi.»
   ⚠️ تعميمُها على كلِّ حركةٍ في الجملة (فتحاتٌ · «ال» · تنوين) أفسدَ ٤٢ مقطعاً من ٤٢ (حكمُ المالك ٢٠٢٦-٠٩-٢٥).
   فالقاعدةُ ضيّقةٌ كالمثال: **في الكلماتِ المستهدفةِ وحدَها**، بعدَ الكسرةِ i وبعدَ الضمّةِ u (والفتحةُ بلا مرافق)،
   وبعدَ الحرفِ الساكنِ نظيرُه اللاتينيُّ كبيراً والحرفُ العربيُّ باقٍ. الشدّةُ تبقى وتتبعُها حركتُها.
   تُطبَّقُ بعدَ liaison() على النصِّ المنطوقِ وحدَه، ولا تمسُّ النصَّ المعروض. */
const LAT = { 'ب':'B','ت':'T','ث':'TH','ج':'J','ح':'H','خ':'KH','د':'D','ذ':'DH','ر':'R','ز':'Z','س':'S','ش':'SH',
  'ص':'S','ض':'D','ط':'T','ظ':'Z','غ':'GH','ف':'F','ق':'Q','ك':'K','ل':'L','م':'M','ن':'N','ه':'H','و':'W','ي':'Y','ة':'T' };
const VOW = { 'َ':'a', 'ُ':'u', 'ِ':'i', 'ً':'an', 'ٌ':'un', 'ٍ':'in' };   // الفتحةُ تُرافَقُ داخلَ الكلمةِ المستهدفةِ وحدَها (تعميمُها على الجملةِ أفسدَ ٤٢/٤٢)
const strip = w => w.replace(/[ً-ْٰ‌ـ.،؟!:؛]/g, '');
function hintWord(w){
  let out = '';
  for (let i = 0; i < w.length; i++) {
    const c = w[i]; out += c;
    if (VOW[c]) { if (w[i + 1] === 'ّ') { out += 'ّ'; i++; } out += VOW[c]; continue; }
    if (c === 'ّ' && VOW[w[i + 1]]) { out += w[i + 1] + VOW[w[i + 1]]; i++; continue; }
    if (c === 'ْ') {
      if (/^[.،؟!:]*$/.test(w.slice(i + 1)) && i > 0 && !/[َُِ]/.test(w[i - 2] || '')) { /* سكونٌ في آخرِ الكلمة: يُرافَق */ }
      let j = i - 1; while (j >= 0 && /[ً-ْٰ]/.test(w[j])) j--;
      const L = LAT[w[j]]; if (L) out += L;
    }
  }
  return out;
}
/* targets: كلماتٌ مستهدفةٌ (مشكولةً أو مجرّدة) — تُرافَقُ هي وحدَها؛ وبلا targets تُرافَقُ الجملةُ كلُّها (لا يُنصَحُ به). */
export function darijat(text, targets){
  const T = targets ? new Set([...targets].map(strip)) : null;
  return text.split(' ').map(w => (!T || T.has(strip(w))) ? hintWord(w) : w).join(' ');
}
